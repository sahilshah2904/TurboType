export function sceneryPolygons(motif: TrackMotif): readonly Shape[] {
  return motifs[motif];
}

export function drawRewardScenery(
  graphics: Phaser.GameObjects.Graphics,
  width: number,
  horizon: number,
  theme: TrackTheme & { motif: TrackMotif },
) {
  const scale = Math.max(0.7, horizon / 120);
  const tile = scale * 240;
  for (let left = -tile / 3; left < width * 2; left += tile)
    sceneryPolygons(theme.motif).forEach((shape, index) => {
      const y = (value: number) => horizon + ((value - 120) * horizon) / 120;
      graphics
        .fillStyle(
          index % 3 === 1 ? theme.detail : theme.land,
          index % 3 === 1 ? 0.58 : 1,
        )
        .beginPath()
        .moveTo(left + shape[0] * scale, y(shape[1]));
      for (let i = 2; i < shape.length; i += 2)
        graphics.lineTo(left + shape[i] * scale, y(shape[i + 1]));
      graphics.closePath().fillPath();
    });
}
